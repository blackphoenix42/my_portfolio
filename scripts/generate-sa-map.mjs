function transliterate(word) {
  let result = "";
  for (const ch of word.toLowerCase()) {
    if (vowels[ch]) result += vowels[ch];
    else if (consonants[ch]) result += consonants[ch];
    else if (ch === "'" || ch === "’") result += "";
    else if (ch === "-") result += "-";
  }
  return result || word;
}

function translateSegment(segment) {
  let text = segment;
  for (const [english, sanskrit] of phrases) {
    text = text.replace(
      new RegExp(`\\b${english.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`, "gi"),
      sanskrit,
    );
  }
  return text.replace(/[A-Za-z]+(?:['’][A-Za-z]+)*/g, (word) => {
    const translated = words[word.toLowerCase()];
    return translated ?? transliterate(word);
  });
}

function translate(value) {
  if (exact[value]) return exact[value];
  if (value.includes("{count, plural,")) {
    return value
      .replace("# golden feather}", "# सुवर्णपक्षम्}")
      .replace("# golden feathers}", "# सुवर्णपक्षाणि}");
  }
  const protectedTokens = [];
  const protectedValue = value.replace(tokenPattern, (token) => {
    const index = protectedTokens.push(token) - 1;
    return `¤${index}¤`;
  });
  const translated = translateSegment(protectedValue).replace(
    /¤(\d+)¤/g,
    (_, index) => protectedTokens[Number(index)],
  );
  return translated.replace(/\s{2,}/g, " ").trim();
}

